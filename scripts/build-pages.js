// ---------- sitemap ----------

function sitemap(groups) {
  const urls = [];
  groups.forEach(({ alternates, lastmod }) => {
    LANGS.forEach(lang => {
      const links = LANGS.map(l => `    <xhtml:link rel="alternate" hreflang="${l}" href="${SITE}${alternates[l]}"/>`)
        .concat([`    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}${alternates.fr}"/>`]);
      urls.push(`  <url>\n    <loc>${SITE}${alternates[lang]}</loc>\n${links.join('\n')}${lastmod ? `\n    <lastmod>${lastmod}</lastmod>` : ''}\n  </url>`);
    });
  });
  SITEMAP_FRENCH_ONLY.forEach(p => urls.push(`  <url>\n    <loc>${SITE}/${p}</loc>\n  </url>`));
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join('\n')}
</urlset>
`;
}

