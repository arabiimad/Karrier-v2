function main() {
  const T = loadTranslations();
  const written = [];
  const groups = [];

  PAGES.forEach(source => {
    LANGS.filter(l => l !== 'fr').forEach(lang => written.push(buildPage(source, lang, T)));
    const alternates = {};
    LANGS.forEach(l => { alternates[l] = pageUrl(l, source.path); });
    groups.push({ alternates });
  });

  const articles = loadArticles();
  const lastUpdate = articles.reduce((max, a) => (a.updated || a.published) > max ? (a.updated || a.published) : max, '');
  LANGS.forEach(lang => {
    written.push(buildBlogIndex(articles, T, lang));
    articles.forEach(a => written.push(buildArticle(a, articles, T, lang)));
  });
  const blogAlternates = {};
  LANGS.forEach(l => { blogAlternates[l] = pageUrl(l, 'blog'); });
  groups.push({ alternates: blogAlternates, lastmod: lastUpdate });
  articles.forEach(a => groups.push({ alternates: articleAlternates(a), lastmod: a.updated || a.published }));

  fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), sitemap(groups));
  written.push('sitemap.xml');
  console.log(`${written.length} files written`);
}

main();
