function loadArticles() {
  const dir = path.join(ROOT, 'content', 'blog');
  return fs.readdirSync(dir)
    .filter(f => f.endsWith('.js'))
    .map(f => {
      const article = require(path.join(dir, f));
      LANGS.forEach(lang => {
        const v = article[lang];
        if (!v || !v.slug || !v.title || !v.description || !v.body) throw new Error(`${f}: ${lang} version is incomplete`);
      });
      return article;
    })
    .sort((a, b) => String(b.published).localeCompare(String(a.published)) || String(a.id).localeCompare(String(b.id)));
}

function formatDate(value, lang) {
  return new Intl.DateTimeFormat(LOCALES[lang], { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(new Date(value + 'T12:00:00Z'));
}

function fill(text, map) {
  return text.replace(/\{(\w+)\}/g, (_, k) => map[k]);
}

function readingMinutes(html) {
  return Math.max(1, Math.round(plainText(html).split(' ').length / 220));
}

// Header and footer of the home page in `lang`, with the language switch turned into links.
function chrome(T, lang, alternates) {
  const { document } = parseHTML(fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8'));
  translate(document, T[lang], lang);
  rewriteLinks(document, lang, true);
  const header = document.querySelector('.site-header');
  const footer = document.querySelector('.site-footer');
  header.querySelectorAll('.nav a[href$="/blog"], .menu-panel a[href$="/blog"]').forEach(a => a.setAttribute('aria-current', 'page'));
  header.querySelectorAll('.langs').forEach(group => {
    group.innerHTML = LANGS.map(l => `<a href="${alternates[l]}" hreflang="${l}" lang="${l}"${l === lang ? ' aria-current="true"' : ''}>${l.toUpperCase()}</a>`).join('');
  });
  return { header: header.outerHTML, footer: footer.outerHTML };
}

