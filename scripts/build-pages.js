// ---------- helpers ----------

function loadTranslations() {
  const code = fs.readFileSync(path.join(ROOT, 'i18n.js'), 'utf8') + '\n;globalThis.__translations = translations;';
  const noop = () => null;
  const ctx = {
    window: { location: { search: '' } },
    location: { search: '', hash: '' },
    document: { addEventListener: noop, documentElement: { getAttribute: noop }, querySelector: noop },
    localStorage: { getItem: noop, setItem: noop },
    URLSearchParams,
    URL
  };
  vm.createContext(ctx);
  vm.runInContext(code, ctx);
  return ctx.__translations;
}

// No trailing slash: vercel.json sets trailingSlash false, so /en/ would redirect to /en.
function pageUrl(lang, p) {
  if (lang === 'fr') return `/${p}`;
  return p ? `/${lang}/${p}` : `/${lang}`;
}

function absolute(lang, p) {
  return SITE + pageUrl(lang, p);
}

function plainText(html) {
  return String(html || '')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

function esc(value) {
  return String(value == null ? '' : value).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
}

// Relative links of a root-level French page, made right for a page in `lang`.
// `fromHome`: a bare #anchor points to the home page (header and footer reused on other pages).
function localUrl(url, lang, fromHome) {
  if (!url) return url;
  if (url.startsWith('#')) return fromHome ? pageUrl(lang, '') + url : url;
  if (/^(https?:|mailto:|tel:|data:|javascript:)/i.test(url)) return url;
  const m = url.match(/^([^?#]*)(\?[^#]*)?(#.*)?$/);
  const raw = m[1].replace(/^\.?\//, '');
  const query = m[2] || '';
  const hash = m[3] || '';
  const p = raw.replace(/\.html$/, '');
  if (p === '' || p === 'index') return pageUrl(lang, '') + query + hash;
  if (p === 'contact' || p === 'blog' || p.startsWith('blog/')) return pageUrl(lang, p) + query + hash;
  if (RUNTIME_PAGES.includes(p)) {
    const params = new URLSearchParams(query.slice(1));
    if (lang !== 'fr') params.set('lang', lang);
    const q = params.toString();
    return `/${p}${q ? '?' + q : ''}${hash}`;
  }
  if (FRENCH_PAGES.includes(p)) return `/${p}${query}${hash}`;
  return `/${raw}${query}${hash}`;
}

function rewriteLinks(root, lang, fromHome) {
  root.querySelectorAll('[href]').forEach(el => {
    if (el.tagName === 'LINK' && /alternate|canonical/.test(el.getAttribute('rel') || '')) return;
    el.setAttribute('href', localUrl(el.getAttribute('href'), lang, fromHome));
  });
  root.querySelectorAll('[src]').forEach(el => el.setAttribute('src', localUrl(el.getAttribute('src'), lang, fromHome)));
}

function setMeta(document, selector, attr, value) {
  const el = document.querySelector(selector);
  if (el && value != null) el.setAttribute(attr, value);
}

// Same work as setLanguage() in i18n.js, done once on the server side.
function translate(document, dict, lang) {
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('data-page-lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = dict[el.getAttribute('data-i18n')];
    if (value == null) return;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.setAttribute('placeholder', value);
    else el.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const value = dict[el.getAttribute('data-i18n-aria')];
    if (value) el.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-wa]').forEach(el => {
    const text = dict['wa_' + el.getAttribute('data-wa')];
    if (text) el.setAttribute('href', WA_LINK + '?text=' + encodeURIComponent(text));
  });
  document.querySelectorAll('button[data-lang]').forEach(btn => {
    const on = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('active', on);
    btn.setAttribute('aria-pressed', on ? 'true' : 'false');
  });
}

function writePage(rel, html) {
  const file = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, html);
  return rel;
}

function serialize(document) {
  const head = document.querySelector('head');
  head.insertBefore(document.createComment(NOTICE), head.firstChild);
  head.insertBefore(document.createTextNode('\n    '), head.firstChild);
  return '<!DOCTYPE html>\n' + document.documentElement.outerHTML + '\n';
}

// ---------- language versions of the French pages ----------

function buildPage(source, lang, T) {
  const dict = T[lang];
  const html = fs.readFileSync(path.join(ROOT, source.file), 'utf8');
  const { document } = parseHTML(html);
  translate(document, dict, lang);

  const titleKey = document.body.getAttribute('data-title-key') || 'page_title';
  const metaKey = document.body.getAttribute('data-meta-key') || (titleKey === 'page_title' ? 'meta_description' : null);
  const title = plainText(dict[titleKey]);
  const description = metaKey ? plainText(dict[metaKey]) : null;
  const url = absolute(lang, source.path);

  document.querySelector('title').textContent = title;
  setMeta(document, 'meta[name="description"]', 'content', description);
  setMeta(document, 'link[rel="canonical"]', 'href', url);
  setMeta(document, 'meta[property="og:url"]', 'content', url);
  setMeta(document, 'meta[property="og:title"]', 'content', title);
  setMeta(document, 'meta[name="twitter:title"]', 'content', title);
  setMeta(document, 'meta[property="og:description"]', 'content', description);
  setMeta(document, 'meta[name="twitter:description"]', 'content', description);
  setMeta(document, 'meta[property="og:locale"]', 'content', OG_LOCALES[lang]);

  document.querySelectorAll('script[type="application/ld+json"]').forEach(script => {
    const data = JSON.parse(script.textContent);
    if (data['@type'] === 'FAQPage') {
      const questions = Object.keys(dict).filter(k => /^faq\d+_q$/.test(k)).sort((a, b) => parseInt(a.slice(3), 10) - parseInt(b.slice(3), 10));
      data.mainEntity = questions.map(q => ({
        '@type': 'Question',
        name: plainText(dict[q]),
        acceptedAnswer: { '@type': 'Answer', text: plainText(dict[q.replace(/_q$/, '_a')]) }
      }));
    }
    if (data['@type'] === 'WebSite') {
      data.description = plainText(dict.meta_description);
      data.inLanguage = lang;
    }
    script.textContent = '\n' + JSON.stringify(data, null, 2).replace(/^/gm, '    ') + '\n    ';
  });

  rewriteLinks(document, lang, false);
  return writePage(path.join(lang, source.file), serialize(document));
}

