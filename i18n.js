// Detect language from browser settings
function detectBrowserLang() {
    const navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (navLang.startsWith('fr')) return 'fr';
    if (navLang.startsWith('es')) return 'es';
    if (navLang.startsWith('de')) return 'de';
    if (navLang.startsWith('en')) return 'en';
    return null;
}

// Detect language from URL parameter
function detectUrlLang() {
    try {
        const params = new URLSearchParams(window.location.search);
        const lang = params.get('lang');
        if (lang && translations[lang]) return lang;
    } catch(e) {}
    return null;
}

// Detect language via IP geolocation (async fallback)
function detectGeoLang(callback) {
    fetch('https://ipapi.co/json/', { signal: AbortSignal.timeout(3000) })
        .then(r => r.json())
        .then(data => {
            const country = (data.country_code || '').toUpperCase();
            const lang = countryLangMap[country] || null;
            callback(lang, country);
        })
        .catch(() => callback(null, null));
}

