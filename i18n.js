const LOCALE_MAP = { fr: 'fr-FR', en: 'en-IE', es: 'es-ES', de: 'de-DE' };
// WhatsApp username link; ?text= prefills the message.
const WA_LINK = 'https://wa.me/@kareer.pro';

function detectUrlLang() {
    try {
        const lang = new URLSearchParams(window.location.search).get('lang');
        if (lang && translations[lang]) return lang;
    } catch (e) {}
    return null;
}

// URL first, then the visitor's last choice, then French.
window.currentLang = (function () {
    const urlLang = detectUrlLang();
    if (urlLang) return urlLang;
    try {
        const saved = localStorage.getItem('kareer_lang');
        if (saved && translations[saved]) return saved;
    } catch (e) {}
    return 'fr';
})();
let currentLang = window.currentLang;

function tr(key) {
    const dict = translations[currentLang] || translations.fr;
    return dict[key] != null ? dict[key] : (translations.fr[key] || '');
}

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    window.currentLang = lang;
    try { localStorage.setItem('kareer_lang', lang); } catch (e) {}
    document.documentElement.lang = lang;

    const dict = translations[lang];
    const titleKey = document.body.getAttribute('data-title-key') || 'page_title';
    if (dict[titleKey]) document.title = dict[titleKey].replace(/&nbsp;/g, ' ');
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && titleKey === 'page_title' && dict.meta_description) metaDesc.setAttribute('content', dict.meta_description);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const value = dict[el.getAttribute('data-i18n')];
        if (value == null) return;
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = value;
        else el.innerHTML = value;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const value = dict[el.getAttribute('data-i18n-aria')];
        if (value) el.setAttribute('aria-label', value);
    });
    document.querySelectorAll('[data-wa]').forEach(el => {
        const text = dict['wa_' + el.getAttribute('data-wa')];
        if (text) el.href = WA_LINK + '?text=' + encodeURIComponent(text);
    });
    document.querySelectorAll('[data-lang]').forEach(btn => {
        const on = btn.getAttribute('data-lang') === lang;
        btn.classList.toggle('active', on);
        if (btn.tagName === 'BUTTON') btn.setAttribute('aria-pressed', on ? 'true' : 'false');
    });

    document.dispatchEvent(new CustomEvent('kareer:lang', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => setLanguage(currentLang));
