function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    try { localStorage.setItem('kareer_lang', lang); } catch(e) {}
    document.documentElement.lang = lang;

    const t = translations[lang];

    // Update document title and meta description
    if (t.page_title) document.title = t.page_title;
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && t.meta_description) metaDesc.setAttribute('content', t.meta_description);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = t[key];
            } else {
                el.innerHTML = t[key];
            }
        }
    });

    // Update aria-label translations
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (t[key]) el.setAttribute('aria-label', t[key]);
    });

    // Update lang switcher UI
    const flagEl = document.getElementById('langFlag');
    const codeEl = document.getElementById('langCode');
    if (flagEl && langMeta[lang]) flagEl.textContent = langMeta[lang].flag;
    if (codeEl && langMeta[lang]) codeEl.textContent = langMeta[lang].code;

    document.querySelectorAll('.lang-option').forEach(opt => {
        opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
    });

    // Update mobile lang buttons
    document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
}

