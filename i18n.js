const langMeta = {
    fr: { flag: '🇫🇷', code: 'FR' },
    en: { flag: '🇬🇧', code: 'EN' },
    es: { flag: '🇪🇸', code: 'ES' },
    de: { flag: '🇩🇪', code: 'DE' }
};

let currentLang = (function(){try{return localStorage.getItem('karrier_lang')}catch(e){return null}})() || 'fr';

function setLanguage(lang) {
    currentLang = lang;
    try { localStorage.setItem('karrier_lang', lang); } catch(e) { /* private browsing */ }
    document.documentElement.lang = lang;

    const t = translations[lang];
    if (!t) return;

    // Update document title and meta description
    if (t.page_title) document.title = t.page_title;
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && t.meta_description) metaDesc.setAttribute('content', t.meta_description);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = t[key];
            } else {
                el.innerHTML = t[key];
            }
        }
    });

    // Update aria-label translations
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (t[key]) el.setAttribute('aria-label', t[key]);
    });

    // Update lang switcher UI
    const flagEl = document.getElementById('langFlag');
    const codeEl = document.getElementById('langCode');
    if (flagEl) flagEl.textContent = langMeta[lang].flag;
    if (codeEl) codeEl.textContent = langMeta[lang].code;

    document.querySelectorAll('.lang-option').forEach(opt => {
        opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
    });
}

// Initialize on load
document.addEventListener('DOMContentLoaded', () => {
    setLanguage(currentLang);
});
